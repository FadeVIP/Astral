'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),http=require('node:http'),crypto=require('node:crypto');
const {PGlite}=require('@electric-sql/pglite');
const {DocumentStore}=require('../store.cjs');
const {RealtimeStore}=require('../realtime-store.cjs');
const {createRealtimeHandler}=require('../realtime-http.cjs');
const {signer,verifier}=require('../service-auth.cjs');
test('realtime HTTP separates public, user and signed service access',async t=>{
 const keys=crypto.generateKeyPairSync('rsa',{modulusLength:2048});
 const account={client_email:'bot@example.test',private_key:keys.privateKey.export({type:'pkcs8',format:'pem'})};
 const sign=signer(account),verify=verifier(account);
 assert.ok(verify(sign()));assert.equal(verify(sign().slice(0,-8)+'abcdefgh'),false);
 const db=await PGlite.create();t.after(()=>db.close());const documents=new DocumentStore(db);await documents.initialize();
 const store=new RealtimeStore(db),handler=createRealtimeHandler({store,documents,verifyService:verify,verifyToken:async token=>{if(token!=='alice')throw Error('bad');return {uid:'alice'};}});
 const server=http.createServer((req,res)=>handler(req,res));await new Promise(r=>server.listen(0,'127.0.0.1',r));t.after(()=>new Promise(r=>server.close(r)));
 const base='http://127.0.0.1:'+server.address().port+'/api/v1/realtime/';
 const req=(path,method='GET',data,auth)=>fetch(base+path+'.json',{method,headers:{...(auth?{Authorization:auth}:{}),'Content-Type':'application/json'},...(data!==undefined?{body:JSON.stringify(data)}:{})});
 assert.equal((await req('chat')).status,503);await db.query(`UPDATE astral_control SET value='"sql"' WHERE key='authority'`);
 assert.equal((await req('chat')).status,200);
 assert.equal((await req('packDailyPrivate')).status,403);
 assert.equal((await req('packOnline','PUT',{count:99},'Bearer alice')).status,403);
 assert.equal((await req('packOnline','PUT',{count:2},'Astral-Service '+sign())).status,200);
 assert.equal((await req('packOnline','PUT',{count:9},'Astral-Service forged')).status,401);
 const p=await req('chat','POST',{uid:'alice',author:'Alice',text:'hi',ts:Date.now()},'Bearer alice');assert.equal(p.status,200);const {name}=await p.json();
 const read=await req('chat/'+name);assert.equal((await read.json()).text,'hi');
 assert.equal((await fetch(base+'chat/'+name+'.json',{headers:{'If-None-Match':read.headers.get('etag')}})).status,304);
 assert.equal((await req('chat/'+name,'DELETE',undefined,'Bearer invalid')).status,401);
 assert.equal((await req('chat/'+name,'DELETE',undefined,'Bearer alice')).status,200);
});
