'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {PGlite}=require('@electric-sql/pglite');
const {DocumentStore}=require('../store.cjs');
const {RealtimeStore,etag,select}=require('../realtime-store.cjs');
test('realtime SQL roundtrip, authority, atomic patches, timestamps and stale writes',async t=>{
 const db=await PGlite.create();t.after(()=>db.close());await new DocumentStore(db).initialize();const s=new RealtimeStore(db);
 const initial={chat:{m1:{text:'hello',ts:1},m2:{text:'world',ts:2}},packOnline:{count:2},scalar:4};
 await assert.rejects(s.mutate('',initial),e=>e.status===503);
 await s.mutate('',initial,{requireAuthority:false});assert.deepEqual(await s.get(),initial);
 await db.query(`UPDATE astral_control SET value='"sql"' WHERE key='authority'`);
 await s.mutate('chat/m1',{text:'edited',updated:{'.sv':'timestamp'}},{patch:true,expected:etag(initial.chat.m1)});
 assert.equal((await s.get('chat/m1')).text,'edited');assert.equal(typeof(await s.get('chat/m1')).updated,'number');
 await assert.rejects(s.mutate('chat/m1',{text:'stale'},{expected:etag(initial.chat.m1)}),e=>e.status===412);
 await assert.rejects(s.mutate('chat',{'m1/text':'forged',m2:null},{patch:true,authorize:()=>{throw Error('denied');}}),/denied/);
 assert.equal((await s.get('chat/m2')).text,'world');
 await assert.rejects(s.mutate('chat',{m1:{},'m1/text':'overlap'},{patch:true}),/Overlapping/);
 await assert.rejects(s.mutate('chat/__proto__/admin',true),/Invalid/);
 await s.mutate('chat/m1',null);assert.equal(await s.get('chat/m1'),null);assert.equal((await s.get('chat/m2')).ts,2);
 assert.deepEqual(select(await s.get('chat'),{orderBy:'ts',startAt:2,limitToLast:1}),{m2:initial.chat.m2});
 assert.equal(await s.get('scalar'),4);
 assert.equal((await db.query("SELECT count(*)::int n FROM astral_realtime WHERE namespace='chat'")).rows[0].n,1);
});
test('bounded query handles null, numeric and tied values deterministically',()=>{
 const rows={a:{ts:3},b:{ts:2},c:{ts:3},d:{}};
 assert.deepEqual(Object.keys(select(rows,{orderBy:'ts',startAt:2,limitToLast:2})),['a','c']);
 assert.deepEqual(Object.keys(select(rows,{orderBy:'ts',equalTo:3})),['a','c']);
 assert.throws(()=>select(rows,{limitToLast:99999}),/Invalid limit/);
});
test('server adapter preserves query windows, removals and transactional updates',async t=>{
 const db=await PGlite.create();t.after(()=>db.close());await new DocumentStore(db).initialize();
 await db.query(`UPDATE astral_control SET value='"sql"' WHERE key='authority'`);
 const s=new RealtimeStore(db),api=require('../realtime-admin.cjs').createRealtimeAdmin(s,{interval:15});t.after(()=>api.stop());
 await api.ref('chat/a').set({ts:1});const q=api.ref('chat').orderByChild('ts').limitToLast(1),added=[],removed=[];
 q.on('child_added',v=>added.push(v.key));q.on('child_removed',v=>removed.push(v.key));
 const until=async fn=>{for(let n=0;n<100&&!fn();n++)await new Promise(r=>setTimeout(r,10));assert.ok(fn());};
 await until(()=>added.length===1);await api.ref('chat/b').set({ts:2});await until(()=>removed.length===1&&added.length===2);
 assert.deepEqual(added,['a','b']);assert.deepEqual(removed,['a']);assert.ok(await s.get('chat/a'));
 const result=await api.ref('counter').transaction(v=>(v||0)+1);assert.equal(result.snapshot.val(),1);
 const canceled=await api.ref('counter').transaction(()=>undefined);assert.equal(canceled.committed,false);
 q.off();
});
test('public clients cannot overwrite statistics, impersonate chat or grant roles',async()=>{
 const {authorizeRealtime,canReadRealtime}=require('../realtime-policy.cjs');
 const c={uid:'alice',admin:false},now=Date.now(),get=async()=>null;
 const write=(path,next,old=null)=>authorizeRealtime(c,{path,next,old,now,get});
 await assert.rejects(write('packOnline',{count:9000}),e=>e.status===403);
 await assert.rejects(write('admins/alice',{role:'admin'}),e=>e.status===403);
 await assert.rejects(write('participants/alice',{uid:'alice',name:'Alice',role:'admin',isAdmin:true}),e=>e.status===403);
 await assert.rejects(write('chat/m',{uid:'bob',author:'Bob',text:'forged',ts:now}),e=>e.status===403);
 await write('chat/m',{uid:'alice',author:'Alice',text:'hello',ts:now});
 await write('packPresence/alice',{seen:now,pack:'astral-1.20.1'});
 await assert.rejects(write('packPresence/bob',{seen:now,pack:'astral-1.20.1'}),e=>e.status===403);
 assert.equal(await canReadRealtime('socialDirectory/sessions/bob',c,get),false);
 assert.equal(await canReadRealtime('packDailyPrivate',c,get),false);
 assert.equal(await canReadRealtime('publicGameData/skins',c,get),true);
});
test('expired browser leases remove own presence and reject another identity',async t=>{
 const db=await PGlite.create();t.after(()=>db.close());const documents=new DocumentStore(db);await documents.initialize();
 await db.query(`UPDATE astral_control SET value='"sql"' WHERE key='authority'`);
 const store=new RealtimeStore(db),leases=require('../realtime-leases.cjs').leases(store,documents);t.after(()=>leases.stop());
 await store.mutate('presence/tab',{uid:'alice',name:'Alice'});
 const id='a'.repeat(32),actions=[{path:'presence/tab',method:'PUT',body:null}];
 await assert.rejects(leases.register(id,{uid:'bob'},actions),e=>e.status===403);
 await leases.register(id,{uid:'alice'},actions);await leases.expire();assert.ok(await store.get('presence/tab'));
 await db.query("UPDATE astral_realtime_leases SET expires_at=clock_timestamp()-interval '1 second'");await leases.expire();assert.equal(await store.get('presence/tab'),null);
 assert.equal((await db.query('SELECT count(*)::int n FROM astral_realtime_leases')).rows[0].n,0);
});
